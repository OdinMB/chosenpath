const SESSION =
  "Story text and images in this game are generated by AI as you play.";
const KIDS =
  "This story is written by an AI. That's a computer program, not a real person. It can make mistakes.";
const REMINDER =
  "Reminder: this story is generated by an AI system, not written by a person.";

/** What the game page does with a choice: sends it */
const sendChoice = jest.fn();

/**
 * A static render mounts the story view afresh, so the beats passed here are
 * the ones the session opened with.
 */
function renderStory(
  beats: Beat[],
  displayedBeatIndex: number | null,
  overrides: Partial<ClientStoryState> = {},
  session: Partial<GameSessionContextType> = {},
  display: { signedIn?: boolean; onLeaveStory?: (to: string) => void } = {}
): string {
  jest.mocked(useStoryBeatState).mockReturnValue({
    displayedBeatIndex,
    showNextBeatPlaceholder: displayedBeatIndex === beats.length,
    localSelectedChoice: undefined,
    beatHistory: beats,
    isViewingLatestBeat: displayedBeatIndex === beats.length - 1,
    latestBeat: beats[beats.length - 1] ?? null,
    navigateToBeat: jest.fn(),
    handleChoiceSelected: jest.fn(),
    showChoiceSent: jest.fn(),
    resetChoice: jest.fn(),
  });
  const storyState = clientStoryState({
    players: { player1: player(beats) },
    ...overrides,
  });
  return renderMarkup(
    <GameSessionContext.Provider
      value={{ ...gameSession(storyState), ...session }}
    >
      <StoryDisplay
        onChoiceSelected={sendChoice}
        onLeaveStory={display.onLeaveStory ?? jest.fn()}
        signedIn={display.signedIn ?? false}
      />
    </GameSessionContext.Provider>
  );
}

function expectNoteAbove(html: string, text: string, marker: string): void {
  const notes = notesIn(html);
  expect(notes).toEqual([
    expect.objectContaining({ name: "AI system", lang: "en", text }),
  ]);
  expect(html.indexOf(marker)).toBeGreaterThan(notes[0]?.offset ?? Infinity);
}

describe("StoryDisplay AI notice", () => {
  it("shows the session notice while the first beat is being written", () => {
    const html = renderStory([], null);

    expect(notesIn(html)).toEqual([
      expect.objectContaining({ name: "AI system", lang: "en", text: SESSION }),
    ]);
  });

  it("shows the session notice above the first beat, on the first paint and once the beat is picked", () => {
    const beats = [beat("Arrival", -1)];

    expectNoteAbove(renderStory(beats, null), SESSION, "[beat: none]");
    expectNoteAbove(renderStory(beats, 0), SESSION, "[beat: Arrival]");
  });

  it("shows the session notice above the beat a returning player resumes on", () => {
    const beats = [beat("Arrival"), beat("Crossroads"), beat("The Pier", -1)];

    expectNoteAbove(renderStory(beats, 2), SESSION, "[beat: The Pier]");
  });

  it("shows the session notice above the next beat when a returning player's choice is still being written", () => {
    const beats = [beat("Arrival"), beat("Crossroads")];

    expectNoteAbove(
      renderStory(beats, 2),
      SESSION,
      "[next beat is being written]"
    );
  });

  it("shows the child-friendly notice instead in read-with-kids stories", () => {
    const html = renderStory([beat("Bedtime", -1)], 0, {
      category: "read-with-kids",
    });

    expectNoteAbove(html, KIDS, "[beat: Bedtime]");
  });

  // The session opened while beat 4 was being written; the player looks back
  const threads = [
    beat("Arrival"),
    beat("The Night Market (1/2)"),
    beat("The Night Market (2/2)"),
    beat("The Old Mill (1/2)"),
  ];

  it.each(["vent-about-reality", "see-your-future-self"] as const)(
    "reminds above the first beat of each Thread in %s stories",
    (category) => {
      expectNoteAbove(
        renderStory(threads, 1, { category }),
        REMINDER,
        "[beat: The Night Market (1/2)]"
      );
      expectNoteAbove(
        renderStory(threads, 3, { category }),
        REMINDER,
        "[beat: The Old Mill (1/2)]"
      );
      expect(notesIn(renderStory(threads, 2, { category }))).toEqual([]);
    }
  );

  it("shows no notice on later beats of other stories", () => {
    for (const category of ["enjoy-fiction", "read-with-kids"] as const) {
      expect(notesIn(renderStory(threads, 1, { category }))).toEqual([]);
    }
  });
});

describe("StoryDisplay when a turn fails", () => {
  const TURN_FAILED = "Unable to continue the story. Please try again.";
  const failed = { turnFailure: { message: TURN_FAILED, at: "[]" } };
  const ALERT = '<div role="alert"';

  it("shows the failure where the next beat's spinner was, and stops the spinner", () => {
    const beats = [beat("Arrival"), beat("Crossroads")];
    const html = renderStory(beats, 2, {}, failed);

    expect(html).toContain("[next beat, no spinner]");
    expect(accessibleText(html)).toContain(`${TURN_FAILED} Try again`);
    expect(html.indexOf(ALERT)).toBeGreaterThan(html.indexOf("[next beat"));
  });

  it("shows the failure below the latest beat when the player's choice failed and its options are open again", () => {
    const beats = [beat("Arrival"), beat("Crossroads", -1)];
    const html = renderStory(beats, 1, {}, failed);

    expect(html.indexOf(ALERT)).toBeGreaterThan(html.indexOf("[beat: Crossroads]"));
  });

  it("shows nothing below an earlier beat the player looks back at", () => {
    const beats = [beat("Arrival"), beat("Crossroads")];

    expect(renderStory(beats, 0, {}, failed)).not.toContain(ALERT);
  });

  it("shows the failure instead of 'Setting up the story...' when the first turn failed", () => {
    const html = renderStory([], null, {}, failed);

    expect(accessibleText(html)).toContain(`${TURN_FAILED} Try again`);
    expect(html).not.toContain("Setting up the story...");
  });

  it("shows no alert while nothing failed", () => {
    expect(renderStory([], null)).not.toContain(ALERT);
    expect(renderStory([beat("Arrival"), beat("Crossroads")], 2)).not.toContain(
      ALERT
    );
  });
});

describe("StoryDisplay's Try again", () => {
  const choiceFailed = {
    turnFailure: {
      message: "Unable to process your choice. Please try again.",
      at: "[]",
    },
  };

  /** Presses the notice's Try again and returns the beat state the display used. */
  function pressTryAgain(): ReturnType<typeof useStoryBeatState> {
    mockNoticeProps[mockNoticeProps.length - 1]!.onTryAgain();
    const results = jest.mocked(useStoryBeatState).mock.results;
    return results[results.length - 1]!.value;
  }

  beforeEach(() => {
    mockNoticeProps.length = 0;
  });

  it("shows the choice it sends again as chosen, as a click on it would, so the options stay closed while it is on its way", () => {
    const tryAgain = jest.fn(() => ({ type: "make_choice" as const, optionIndex: 2 }));
    renderStory([beat("Arrival"), beat("Crossroads", -1)], 1, {}, {
      ...choiceFailed,
      tryAgain,
    });

    const beatState = pressTryAgain();

    expect(tryAgain).toHaveBeenCalledTimes(1);
    expect(beatState.showChoiceSent).toHaveBeenCalledWith(2);
  });

  it("leaves the options alone when it asks the server for the turn instead", () => {
    const tryAgain = jest.fn(() => ({ type: "retry_turn" as const }));
    renderStory([beat("Arrival"), beat("Crossroads")], 2, {}, {
      ...choiceFailed,
      tryAgain,
    });

    const beatState = pressTryAgain();

    expect(tryAgain).toHaveBeenCalledTimes(1);
    expect(beatState.showChoiceSent).not.toHaveBeenCalled();
  });

  it("hides a refused choice's notice before it sends, as a click on a choice does", () => {
    const tryAgain = jest.fn(() => ({ type: "make_choice" as const, optionIndex: 2 }));
    const clearChoiceLimit = jest.fn();
    renderStory([beat("Arrival"), beat("Crossroads", -1)], 1, {}, {
      ...choiceFailed,
      tryAgain,
      clearChoiceLimit,
    });

    pressTryAgain();

    expect(clearChoiceLimit).toHaveBeenCalledTimes(1);
    expect(clearChoiceLimit.mock.invocationCallOrder[0]).toBeLessThan(
      tryAgain.mock.invocationCallOrder[0]!
    );
  });
});

describe("StoryDisplay when the player's choice was refused for choosing too fast", () => {
  const REFUSED = "Your choice wasn't sent";
  // Where the notice is in the markup (which escapes the apostrophe above)
  const NOTICE = "choosing faster than the game allows";
  const LIVE_REGION = '<div aria-live="polite"';
  const limited = () => ({
    choiceLimit: { until: Date.now() + 12_000, at: "[]" },
  });

  beforeEach(() => {
    mockBeatProps.length = 0;
    sendChoice.mockClear();
  });

  // Where the beat shows it (above its open choices, and only then) is BeatContentChoiceNotice.test.tsx
  it("hands the beat the notice for its choices, in a polite live region", () => {
    const html = renderStory([beat("Arrival"), beat("Crossroads", -1)], 1, {}, limited());

    expect(accessibleText(html)).toContain(REFUSED);
    expect(html.indexOf(LIVE_REGION)).toBeGreaterThan(html.indexOf("[beat: Crossroads]"));
    expect(html.indexOf(LIVE_REGION)).toBeLessThan(html.indexOf(NOTICE));
  });

  it("hands the beat the empty live region while nothing was refused, so a refusal is announced", () => {
    const html = renderStory([beat("Arrival"), beat("Crossroads", -1)], 1);

    expect(html).toContain(`[beat: Crossroads]${LIVE_REGION}></div>`);
  });

  it("says nothing while the next beat is being written", () => {
    const html = renderStory([beat("Arrival"), beat("Crossroads")], 2, {}, limited());

    expect(html).not.toContain(NOTICE);
  });

  it("hides the notice as the player chooses again, before the choice is sent", () => {
    const clearChoiceLimit = jest.fn();
    renderStory([beat("Arrival"), beat("Crossroads", -1)], 1, {}, {
      ...limited(),
      clearChoiceLimit,
    });

    mockBeatProps[mockBeatProps.length - 1]!.onChoiceSelected(1);

    expect(clearChoiceLimit).toHaveBeenCalledTimes(1);
    expect(sendChoice).toHaveBeenCalledWith(1);
    expect(clearChoiceLimit.mock.invocationCallOrder[0]).toBeLessThan(
      sendChoice.mock.invocationCallOrder[0]!
    );
  });
});

describe("StoryDisplay at the story's end", () => {
  const ended = [beat("Arrival"), beat("Crossroads"), beat("The End", -1)];
  const lastRecap = (): RecapProps => mockRecapProps[mockRecapProps.length - 1]!;

  beforeEach(() => {
    mockRecapProps.length = 0;
  });

  it("shows the recap below the ending, from the player's beats and the story's stats", () => {
    const html = renderStory(ended, 2, { gameOver: true });

    expect(html.indexOf("[recap]")).toBeGreaterThan(html.indexOf("[beat: The End]"));
    expect(lastRecap().beats).toBe(ended);
    expect(lastRecap().stats).toEqual(
      expect.objectContaining({ playerStats: [], sharedStats: [] })
    );
  });

  it("hands the recap where the story's outcomes ended, as the state says", () => {
    const outcomesAtEnd = [
      { id: "shared_harbour", owner: "shared" as const, question: "Does the harbour reopen?", milestones: ["The fleet sails home."], intended: 1, complete: true },
    ];
    renderStory(ended, 2, { gameOver: true, outcomesAtEnd });

    expect(lastRecap().outcomes).toBe(outcomesAtEnd);
  });

  it("leaves through the game's own exit, which knows whether the player has an account", () => {
    const onLeaveStory = jest.fn();
    renderStory(ended, 2, { gameOver: true }, {}, { onLeaveStory, signedIn: true });

    expect(lastRecap().onLeave).toBe(onLeaveStory);
    expect(lastRecap().signedIn).toBe(true);
  });

  it("shows no recap while the story goes on", () => {
    expect(renderStory(ended, 2, { gameOver: false })).not.toContain("[recap]");
  });

  it("shows no recap on an earlier beat the player looks back at", () => {
    const html = renderStory(ended, 0, { gameOver: true });

    expect(html).toContain("[beat: Arrival]");
    expect(html).not.toContain("[recap]");
  });
});
